import CryptoKit
import Foundation
import Testing
@testable import EarshotKit

/// Cross-checks between this Swift code and the web client in `web/src/engine`.
///
/// The Swift code is the specification. These tests make sure the browser speaks it byte for byte:
///
/// 1. `writeVectors` saves real bytes made by the Swift code — keys, tags, beacons, invitations,
///    every message type, and a whole encrypted conversation made with fixed keys — to
///    `web/tests/unit/fixtures/swift-vectors.json`. The web tests check that TypeScript makes
///    exactly the same bytes and understands them. It only writes when asked:
///
///        EARSHOT_WRITE_VECTORS=1 swift test --filter WebVectors
///
/// 2. `acceptsWebClientOutput` reads `web/tests/unit/fixtures/ts-vectors.json` (written by the web
///    tests) and checks that this Swift code accepts every byte the browser would send.
@Suite("Web client vectors")
struct WebVectorsTests {
    /// `<repo>/web/tests/unit/fixtures`, found from this file's own location.
    static let fixtures = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent() // EarshotKitTests
        .deletingLastPathComponent() // Tests
        .deletingLastPathComponent() // EarshotKit
        .deletingLastPathComponent() // repository root
        .appendingPathComponent("web/tests/unit/fixtures", isDirectory: true)

    // Fixed inputs. The same numbers are written into the fixture, so the web tests read them from there.
    static func counting(from start: UInt8, count: Int = 32) -> Data { Data((0..<count).map { start &+ UInt8($0) }) }
    static let phoneSeed = counting(from: 0x01)
    static let webSeed = counting(from: 0x41)
    static let phoneEphemeralSeed = counting(from: 0x81)
    static let webEphemeralSeed = counting(from: 0xC1)
    static let phoneNonce = Data([0xA1, 0xA2, 0xA3, 0xA4, 0xA5, 0xA6, 0xA7, 0xA8])
    static let webNonce = Data([0xB1, 0xB2, 0xB3, 0xB4, 0xB5, 0xB6, 0xB7, 0xB8])
    static let textID = UUID(uuidString: "3F2504E0-4F89-11D3-9A0C-0305E82C3301")!
    static let ackID = UUID(uuidString: "E621E1F8-C36C-495A-93FC-0C247A3E6E5F")!

    // MARK: Swift -> web

    @Test func writeVectors() throws {
        guard ProcessInfo.processInfo.environment["EARSHOT_WRITE_VECTORS"] != nil else { return }
        let phone = try Identity(rawRepresentation: Self.phoneSeed)
        let web = try Identity(rawRepresentation: Self.webSeed)
        let phoneHandshake = Handshake(fixedEphemeral: try .init(rawRepresentation: Self.phoneEphemeralSeed))
        let webHandshake = Handshake(fixedEphemeral: try .init(rawRepresentation: Self.webEphemeralSeed))
        let phoneEph = phoneHandshake.publicKey, webEph = webHandshake.publicKey

        var out: [String: Any] = [:]
        out["about"] = "Generated by EarshotKit/Tests/EarshotKitTests/WebVectorsTests.swift. Do not edit by hand."
        out["inputs"] = [
            "phoneSeed": hex(Self.phoneSeed), "webSeed": hex(Self.webSeed),
            "phoneEphemeralSeed": hex(Self.phoneEphemeralSeed), "webEphemeralSeed": hex(Self.webEphemeralSeed),
            "phoneNonce": hex(Self.phoneNonce), "webNonce": hex(Self.webNonce),
        ]
        out["identities"] = [
            "phonePublicKey": hex(phone.publicKey), "phoneContactID": phone.contactID.rawValue,
            "webPublicKey": hex(web.publicKey), "webContactID": web.contactID.rawValue,
            "phoneEphemeralPublic": hex(phoneEph), "webEphemeralPublic": hex(webEph),
        ]
        out["safetyCode"] = SafetyCode.make(phone.publicKey, web.publicKey)
        out["safetyCodeSwapped"] = SafetyCode.make(web.publicKey, phone.publicKey)
        out["discoveryTag"] = ["identityKey": hex(phone.publicKey), "nonce": hex(Self.phoneNonce),
                               "tag": hex(DiscoveryTag.make(identityKey: phone.publicKey, nonce: Self.phoneNonce))]
        let pairTag = PairTag.make(web.publicKey, phone.publicKey, inviterNonce: Self.webNonce, inviteeNonce: Self.phoneNonce)
        out["pairTag"] = ["a": hex(web.publicKey), "b": hex(phone.publicKey), "inviterNonce": hex(Self.webNonce),
                          "inviteeNonce": hex(Self.phoneNonce), "tag": hex(pairTag)]
        out["knock"] = ["own": hex(web.publicKey), "peer": hex(phone.publicKey), "signerEphemeral": hex(webEph),
                        "peerEphemeral": hex(phoneEph),
                        "knock": hex(Knock.make(ownIdentityKey: web.publicKey, peerIdentityKey: phone.publicKey,
                                                signerEphemeral: webEph, peerEphemeral: phoneEph))]

        let tag8 = DiscoveryTag.make(identityKey: phone.publicKey, nonce: Self.phoneNonce)
        out["beacons"] = ["Maya Okafor", "Zoë 🌙", "", String(repeating: "é", count: 48)].map { name -> [String: Any] in
            let ad = LocalAdvertisement(displayName: name, nonce: Self.phoneNonce, tag: tag8, isVisible: true)
            return ["name": name, "nonce": hex(Self.phoneNonce), "tag": hex(tag8), "bytes": hex(BluetoothWire.beacon(ad))]
        }

        let newContext = InviteContext(name: "Alex", nonce: Self.webNonce)
        let tagged = InviteContext(nonce: Self.webNonce, tag: pairTag)
        out["invites"] = [("request", newContext), ("reconnection", tagged)].map { label, context -> [String: Any] in
            // Encode once: Swift's JSONEncoder may order keys differently on every call.
            let json = context.encoded()
            let body = BluetoothWire.inviteBody(nonce: Self.webNonce, context: json)
            return ["label": label, "contextJSON": String(decoding: json, as: UTF8.self),
                    "nonce": hex(Self.webNonce), "name": context.name as Any, "tag": context.tag.map(hex) as Any,
                    "body": hex(body), "frame": hex(BluetoothWire.frame(.invite, body))]
        }
        out["simpleFrames"] = [
            "accept": hex(BluetoothWire.frame(.accept)), "decline": hex(BluetoothWire.frame(.decline)),
            "close": hex(BluetoothWire.frame(.close)),
            "dataHello": hex(BluetoothWire.frame(.data, Frame.hello(version: 1, ephemeralKey: webEph).encoded())),
        ]

        let samples: [(String, Payload)] = [
            ("knock", .knock(Self.counting(from: 0, count: 32))),
            ("auth", .auth(.init(identityKey: phone.publicKey, name: "Maya \"M\" Okafor/ü",
                                 signature: Self.counting(from: 0x10, count: 64)))),
            ("text", .text(.init(id: Self.textID, text: "Line one\nline \"two\" / slash 👋🏽 \u{1F}end"))),
            ("ack", .ack(Self.ackID)),
            ("bye", .bye),
        ]
        out["payloads"] = try samples.map { name, payload in
            ["case": name, "json": String(decoding: try payload.encoded(), as: UTF8.self)]
        }

        let chunkSource = Data((0..<400).map { UInt8(truncatingIfNeeded: $0 * 7) })
        out["chunks"] = [180, 20].map { length -> [String: Any] in
            ["frame": hex(chunkSource), "maxChunkLength": length,
             "chunks": BluetoothWire.chunks(of: chunkSource, maxChunkLength: length).map(hex)]
        }

        // A full encrypted conversation with fixed keys. The web test reproduces every web -> phone
        // frame byte for byte and opens every phone -> web frame.
        var phoneChannel = try phoneHandshake.channel(remoteEphemeral: webEph)
        var webChannel = try webHandshake.channel(remoteEphemeral: phoneEph)
        let phoneAuth = Payload.auth(.init(identityKey: phone.publicKey, name: "Maya Okafor",
            signature: try phone.sign(Handshake.transcript(signerEphemeral: phoneEph, peerEphemeral: webEph))))
        let webAuth = Payload.auth(.init(identityKey: web.publicKey, name: "Alex",
            signature: try web.sign(Handshake.transcript(signerEphemeral: webEph, peerEphemeral: phoneEph))))
        let script: [(String, Payload)] = [
            ("web", .knock(Knock.make(ownIdentityKey: web.publicKey, peerIdentityKey: phone.publicKey,
                                      signerEphemeral: webEph, peerEphemeral: phoneEph))),
            ("phone", .knock(Knock.make(ownIdentityKey: phone.publicKey, peerIdentityKey: web.publicKey,
                                        signerEphemeral: phoneEph, peerEphemeral: webEph))),
            ("web", webAuth),
            ("phone", phoneAuth),
            ("web", .text(.init(id: Self.textID, text: "hello from the browser"))),
            ("phone", .ack(Self.textID)),
            ("phone", .text(.init(id: Self.ackID, text: "Echo: hello from the browser"))),
            ("web", .ack(Self.ackID)),
            ("web", .bye),
        ]
        var records: [[String: Any]] = []
        for (from, payload) in script {
            let plaintext = try payload.encoded()
            let sealed = from == "web" ? try webChannel.seal(plaintext) : try phoneChannel.seal(plaintext)
            let frame = Frame.sealed(sealed).encoded()
            // Check that the other side opens it, so the fixture is known to be good.
            let opened = from == "web" ? try phoneChannel.open(sealed) : try webChannel.open(sealed)
            #expect(opened == plaintext)
            records.append(["from": from, "plaintext": hex(plaintext), "frame": hex(frame),
                            "bluetooth": hex(BluetoothWire.frame(.data, frame))])
        }
        out["transcript"] = [
            "phoneHello": hex(Frame.hello(version: Handshake.version, ephemeralKey: phoneEph).encoded()),
            "webHello": hex(Frame.hello(version: Handshake.version, ephemeralKey: webEph).encoded()),
            "records": records,
        ]

        try FileManager.default.createDirectory(at: Self.fixtures, withIntermediateDirectories: true)
        let data = try JSONSerialization.data(withJSONObject: out, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
        try data.write(to: Self.fixtures.appendingPathComponent("swift-vectors.json"))
    }

    // MARK: web -> Swift

    @Test func acceptsWebClientOutput() throws {
        let url = Self.fixtures.appendingPathComponent("ts-vectors.json")
        guard FileManager.default.fileExists(atPath: url.path) else {
            // Written by `npm test` in web/. Nothing to check until it exists.
            return
        }
        let root = try #require(try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any])
        func obj(_ value: Any?) throws -> [String: Any] { try #require(value as? [String: Any]) }
        func str(_ value: Any?) throws -> String { try #require(value as? String) }
        func data(_ value: Any?) throws -> Data { try unhex(try str(value)) }

        let inputs = try obj(root["inputs"])
        let phone = try Identity(rawRepresentation: try data(inputs["phoneSeed"]))
        let web = try Identity(rawRepresentation: try data(inputs["webSeed"]))
        let phoneNonce = try data(inputs["phoneNonce"]), webNonce = try data(inputs["webNonce"])
        let phoneHandshake = Handshake(fixedEphemeral: try .init(rawRepresentation: try data(inputs["phoneEphemeralSeed"])))
        let webEphemeral = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: try data(inputs["webEphemeralSeed"]))
        let phoneEph = phoneHandshake.publicKey, webEph = webEphemeral.publicKey.rawRepresentation

        let ids = try obj(root["identities"])
        #expect(try data(ids["webPublicKey"]) == web.publicKey)
        #expect(try str(ids["webContactID"]) == web.contactID.rawValue)
        #expect(try data(ids["webEphemeralPublic"]) == webEph)
        #expect(try str(root["safetyCode"]) == SafetyCode.make(phone.publicKey, web.publicKey))
        #expect(try data(obj(root["discoveryTag"])["tag"]) == DiscoveryTag.make(identityKey: web.publicKey, nonce: webNonce))
        let pairTag = PairTag.make(web.publicKey, phone.publicKey, inviterNonce: webNonce, inviteeNonce: phoneNonce)
        #expect(try data(obj(root["pairTag"])["tag"]) == pairTag)
        let knock = Knock.make(ownIdentityKey: web.publicKey, peerIdentityKey: phone.publicKey,
                               signerEphemeral: webEph, peerEphemeral: phoneEph)
        #expect(try data(obj(root["knock"])["knock"]) == knock)

        // Every payload the browser can send decodes to the expected value.
        let payloads = try #require(root["payloads"] as? [[String: Any]])
        #expect(payloads.count == 5)
        for sample in payloads {
            let decoded = try Payload.decode(Data(try str(sample["json"]).utf8))
            let expected: Payload
            switch try str(sample["case"]) {
            case "knock": expected = .knock(try data(sample["knock"]))
            case "auth": expected = .auth(.init(identityKey: try data(sample["identityKey"]), name: try str(sample["name"]),
                                                signature: try data(sample["signature"])))
            case "text": expected = .text(.init(id: try #require(UUID(uuidString: try str(sample["id"]))), text: try str(sample["text"])))
            case "ack": expected = .ack(try #require(UUID(uuidString: try str(sample["id"]))))
            case "bye": expected = .bye
            default: Issue.record("unknown payload case"); continue
            }
            #expect(decoded == expected)
        }

        // Invitations: the context JSON and the framing around it.
        let invites = try #require(root["invites"] as? [[String: Any]])
        #expect(invites.count == 2)
        for invite in invites {
            let parsed = try #require(BluetoothWire.parseFrame(try data(invite["frame"])))
            #expect(parsed.kind == .invite)
            let body = try #require(BluetoothWire.parseInviteBody(parsed.body))
            #expect(body.nonce == webNonce)
            let context = try #require(InviteContext.decode(body.context))
            #expect(context.v == 1)
            #expect(context.nonce == webNonce)
            #expect(context.name == invite["name"] as? String)
            if invite["tag"] is String {
                #expect(context.tag == pairTag, "the phone must recognise the reconnection tag")
            } else {
                #expect(context.tag == nil)
            }
        }

        let beacon = try obj(root["beacon"])
        let ad = try #require(BluetoothWire.parseBeacon(try data(beacon["bytes"])))
        #expect(ad.displayName == (try str(beacon["name"])))
        #expect(ad.nonce == (try data(beacon["nonce"])))

        // Chunking: the same cut points as Swift, and Swift reassembles them.
        for sample in try #require(root["chunks"] as? [[String: Any]]) {
            let frame = try data(sample["frame"])
            let chunks = try #require(sample["chunks"] as? [String]).map(unhex)
            let length = try #require(sample["maxChunkLength"] as? Int)
            #expect(chunks == BluetoothWire.chunks(of: frame, maxChunkLength: length))
            var reassembler = BluetoothWire.Reassembler()
            var result: Data?
            for chunk in chunks { result = try reassembler.append(chunk) }
            #expect(result == frame)
        }

        // The browser's half of an encrypted conversation, opened by the Swift channel.
        let transcript = try obj(root["transcript"])
        guard case .hello(let version, let key) = try Frame(decoding: try data(transcript["webHello"])) else {
            Issue.record("web hello did not decode as a hello frame")
            return
        }
        #expect(version == Handshake.version)
        #expect(key == webEph)
        var channel = try phoneHandshake.channel(remoteEphemeral: key)
        let records = try #require(transcript["records"] as? [[String: Any]])
        #expect(records.count >= 4)
        for record in records {
            guard case .sealed(let box) = try Frame(decoding: try data(record["frame"])) else {
                Issue.record("expected a sealed frame")
                continue
            }
            let plaintext = try channel.open(box)
            #expect(plaintext == (try data(record["plaintext"])))
            if case .auth(let auth) = try Payload.decode(plaintext) {
                #expect(auth.identityKey == web.publicKey)
                #expect(Identity.verify(signature: auth.signature,
                                        of: Handshake.transcript(signerEphemeral: webEph, peerEphemeral: phoneEph),
                                        identityKey: auth.identityKey))
            }
        }
    }
}

private func hex(_ data: Data) -> String { data.map { String(format: "%02x", $0) }.joined() }

private func unhex(_ string: String) throws -> Data {
    var bytes: [UInt8] = []
    var index = string.startIndex
    while index < string.endIndex {
        let next = try #require(string.index(index, offsetBy: 2, limitedBy: string.endIndex))
        bytes.append(try #require(UInt8(string[index..<next], radix: 16)))
        index = next
    }
    return Data(bytes)
}
